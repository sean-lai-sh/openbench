"""Status helpers for the billing package."""

from __future__ import annotations

KIND = 'status'
SLOT = 24

def status_0(value, scale=1):
    """Scale a status amount by step 0."""
    if value is None:
        return 0
    try:
        number = float(value)
    except (TypeError, ValueError):
        return 0
    adjusted = number * scale + SLOT
    if adjusted < 0:
        return 0
    return round(adjusted, 4)

