"""Import + no-network validation pipeline for Harbor-format tasks (SEA-106).

Sources: TB2 @ 2fd12b88 and TB Pro @ 82bc46de (both Harbor format), and TB1
core 0.1.1 @ 91e10457 after ``tb1_to_harbor``. Three steps, all resumable:

``plan``
    Reads every source and dedupes, both by name and by normalized
    instruction text, in source priority order: tasks already in the repo,
    then the order given. A task found earlier wins, so TB Pro tasks that
    duplicate TB2 or TB1 core are dropped. Writes ``plan.json``.

``run`` (Docker; on the VM)
    For each planned task:
    1. Pin the environment image (pull + repo digest), or build it from
       ``environment/`` and record its image id and base-image digests.
    2. Copy the starting workspace out of the image's WORKDIR.
    3. Build the derived task image (``checker_data/image/Dockerfile``): the
       environment plus the verifier's dependencies, primed by running the
       upstream ``tests/test.sh`` once at build time with network, then
       ``UV_OFFLINE=1 PIP_NO_INDEX=1``. The agent and the checker both use
       it (``task.toml`` ``docker_image``), as in the openbench-tb-mid pack.
    4. Write ``checker.sh``. It runs upstream ``tests/test.sh`` with
       ``--network none``, plus the upstream ``solve.sh`` first when the
       solution overlay is on. Reward comes from ``/logs/verifier/reward.txt``.
    5. Validate polarity with ``obench.validate_tasks.run_checker`` (what
       ``obench validate`` runs): the untouched workspace must fail and the
       solution must pass, with no network.

    A task that fails any step is moved to ``<out>/_dropped/<task>/`` and its
    reason recorded.

``report``
    Writes ``IMPORT_REPORT.md`` and per-source counts from ``import-report.jsonl``.

Known limitation (documented in README.md): only the workspace (WORKDIR)
carries from the agent's run to the checker, the same as the repo's existing
TB2 imports. A task whose check depends on system state the agent changed
outside WORKDIR is graded on a fresh container.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

from obench.taskimport.docker import Docker, DockerError

PLAN_SCHEMA = "openbench.taskimport.plan/v1"
REPORT_SCHEMA = "openbench.taskimport.report/v1"
NETWORK_HINTS = re.compile(r"(Could not resolve host|Temporary failure in name resolution|Network is unreachable|"
                           r"Failed to (download|fetch|connect)|No route to host|offline mode|--offline|"
                           r"Connection refused|ConnectionError|getaddrinfo)", re.IGNORECASE)

CHECKER_SH = """#!/bin/bash
# Generated by obench.taskimport.pipeline. The image comes from the runner (BENCH_TASK_IMAGE); the literal below is
# the hand-run fallback. task.toml owns the image.
set -uo pipefail
IMAGE="${{BENCH_TASK_IMAGE:-{image}}}"
WORKDIR={workdir}
LOG_DIR="$(mktemp -d "${{TMPDIR:-/tmp}}/obench-verifier.XXXXXX")"
trap 'rm -rf "$LOG_DIR"' EXIT
docker run --rm --network none --platform "${{DOCKER_PLATFORM:-{platform}}}" -e OPENBENCH_SOLUTION_OVERLAY \\
  -v "$PWD:$WORKDIR" -v "$TASK_DIR/checker_data/tests:/tests:ro" -v "$TASK_DIR/checker_data/oracle:/openbench-oracle:ro" \\
  -v "$LOG_DIR:/logs/verifier" -w "$WORKDIR" "$IMAGE" bash -c '
    if [ "${{OPENBENCH_SOLUTION_OVERLAY:-}}" = "1" ]; then
      bash /openbench-oracle/solve.sh >/tmp/oracle.log 2>&1 || {{ tail -50 /tmp/oracle.log >&2; exit 2; }}
    fi
    bash /tests/test.sh'
rc=$?
reward="$(tr -d '[:space:]' < "$LOG_DIR/reward.txt" 2>/dev/null || true)"
case "$reward" in 1|1.0|1.00|1.000) echo "SCORE: 1.0"; exit 0 ;; esac
echo "SCORE: 0"
echo "FAIL: reward=${{reward:-missing}} (container exit $rc)"
exit 1
"""

DERIVED_DOCKERFILE = """# Generated by obench.taskimport.pipeline: environment + verifier dependencies, primed with network at build time.
FROM {env_ref}
USER root
COPY tests/ /openbench-prime/tests/
RUN mkdir -p /logs/verifier /tests /tmp/openbench-prime-work \\
 && cp -r /openbench-prime/tests/. /tests/ \\
 && cd /tmp/openbench-prime-work && (TEST_DIR=/tests bash /tests/test.sh > /tmp/openbench-prime.log 2>&1 || true) \\
 && rm -rf /tests /openbench-prime /tmp/openbench-prime-work && rm -rf /logs/verifier/*
ENV UV_OFFLINE=1 PIP_NO_INDEX=1
WORKDIR {workdir}
{user_line}"""


@dataclass(frozen=True)
class Source:
    name: str          # collection name, e.g. terminal-bench-2
    root: Path         # directory holding Harbor task dirs
    repo: str
    commit: str
    license: str = "Apache-2.0"


def normalize_instruction(text: str) -> str:
    return hashlib.sha256(re.sub(r"\s+", " ", text).strip().lower().encode("utf-8")).hexdigest()


def harbor_tasks(root: Path) -> list[Path]:
    return sorted(p for p in Path(root).iterdir()
                  if p.is_dir() and (p / "task.toml").is_file() and (p / "instruction.md").is_file())


def existing_repo_tasks(repo_root: Path) -> dict[str, str]:
    """``{task id: relative dir}`` for every OpenBench task already in the repo."""
    found = {}
    for checker in sorted(Path(repo_root).glob("**/checker.sh")):
        d = checker.parent
        rel = d.relative_to(repo_root)
        if (d / "instruction.md").is_file() and rel.parts[0] not in ("obench", ".git", "results") and "_dropped" not in rel.parts:
            found.setdefault(d.name, str(rel))
    return found


def plan(sources: list[Source], repo_root: Path) -> dict:
    existing = existing_repo_tasks(repo_root)
    existing_hashes = {}
    for task, rel in existing.items():
        instr = Path(repo_root) / rel / "instruction.md"
        existing_hashes.setdefault(normalize_instruction(instr.read_text(encoding="utf-8")), f"repo:{rel}")
    seen_names = {name: f"repo:{rel}" for name, rel in existing.items()}
    seen_hashes = dict(existing_hashes)
    entries = []
    for source in sources:
        for task_dir in harbor_tasks(source.root):
            task = task_dir.name
            digest = normalize_instruction((task_dir / "instruction.md").read_text(encoding="utf-8"))
            if task in seen_names:
                decision, dup = "duplicate_name", seen_names[task]
            elif digest in seen_hashes:
                decision, dup = "duplicate_instruction", seen_hashes[digest]
            else:
                decision, dup = "import", None
                seen_names[task] = f"{source.name}:{task}"
                seen_hashes[digest] = f"{source.name}:{task}"
            entries.append({"source": source.name, "task": task, "path": str(task_dir), "decision": decision,
                            "duplicate_of": dup, "instruction_sha256": digest})
    return {"schema": PLAN_SCHEMA, "sources": [{"name": s.name, "root": str(s.root), "repo": s.repo,
                                                "commit": s.commit, "license": s.license} for s in sources],
            "entries": entries}


def _toml(path: Path) -> dict:
    return tomllib.loads(path.read_text(encoding="utf-8"))


def _dockerfile_bases(dockerfile: Path) -> list[str]:
    return re.findall(r"(?im)^\s*FROM\s+(?:--platform=\S+\s+)?(\S+)", dockerfile.read_text(encoding="utf-8"))


def _q(value) -> str:
    return json.dumps(str(value))


class Importer:
    def __init__(self, out_root: Path, docker: Docker | None = None,
                 validate: Callable[[str, bool], tuple[int, str, float | None]] | None = None):
        self.out_root, self.docker = Path(out_root), docker or Docker()
        if validate is None:
            from obench.validate_tasks import run_checker as validate
        self.validate = validate

    def import_task(self, entry: dict, source: Source) -> dict:
        task, src = entry["task"], Path(entry["path"])
        out = self.out_root / source.name / task
        row = {"schema": REPORT_SCHEMA, "source": source.name, "task": task, "upstream_repo": source.repo,
               "upstream_commit": source.commit, "status": None, "stage": None, "reason": None}
        try:
            meta = _toml(src / "task.toml")
            env = meta.get("environment") or {}
            if (env.get("gpus") or 0) > 0:
                return self._drop(row, out, "plan", f"needs {env['gpus']} GPU(s)")
            env_ref, env_record = self._environment(src, source, task, env)
            row["stage"] = "workspace"
            workdir = self.docker.workdir(env_ref)
            if workdir in ("", "/"):
                return self._drop(row, out, "workspace", "environment image sets no WORKDIR")
            if out.exists():
                shutil.rmtree(out)
            (out / "workspace").mkdir(parents=True)
            self.docker.copy_out(env_ref, workdir, str(out / "workspace"))
            row["stage"] = "files"
            self._write_files(src, out, meta, workdir)
            row["stage"] = "derived_image"
            tag = f"openbench-{source.name}-{task}:pinned".lower()
            user = (self.docker.inspect(env_ref).get("Config") or {}).get("User") or ""
            (out / "checker_data" / "image").mkdir(parents=True, exist_ok=True)
            (out / "checker_data" / "image" / "Dockerfile").write_text(DERIVED_DOCKERFILE.format(
                env_ref=env_ref, workdir=workdir, user_line=f"USER {user}\n" if user else ""), encoding="utf-8")
            self.docker.build(str(out / "checker_data"), tag, dockerfile=str(out / "checker_data" / "image" / "Dockerfile"))
            derived_id = self.docker.image_id(tag)
            (out / "checker.sh").write_text(CHECKER_SH.format(image=tag, workdir=workdir, platform=self.docker.platform),
                                            encoding="utf-8")
            os.chmod(out / "checker.sh", 0o755)
            timeout = int(float((meta.get("verifier") or {}).get("timeout_sec") or 600))
            (out / "task.toml").write_text("\n".join([
                f"docker_image = {_q(tag)}", f"docker_image_id = {_q(derived_id)}", f"docker_workdir = {_q(workdir)}",
                f"checker_timeout_s = {timeout + 300}", f"agent_timeout_s = {int(float((meta.get('agent') or {}).get('timeout_sec') or 1800))}",
                f"upstream_repo = {_q(source.repo)}", f"upstream_commit = {_q(source.commit)}",
                f"upstream_task = {_q(task)}", f"collection = {_q(source.name)}", ""]), encoding="utf-8")
            self._provenance(out, source, task, env_record, tag, derived_id, workdir)
            row["stage"] = "validate"
            ws_code, ws_out, _ = self.validate(str(out), False)
            if ws_code == 0:
                return self._drop(row, out, "validate", "untouched workspace passes the checker (expected failure)")
            sol_code, sol_out, _ = self.validate(str(out), True)
            if sol_code != 0:
                hint = "verifier or oracle needs network" if NETWORK_HINTS.search(sol_out or "") else "solution fails the checker"
                tail = " | ".join((sol_out or "").strip().splitlines()[-3:])[:300]
                return self._drop(row, out, "validate", f"{hint}: {tail}")
            row.update({"status": "admitted", "stage": "done", "image": tag, "image_id": derived_id,
                        "env_image": env_record, "workdir": workdir})
            return row
        except DockerError as exc:
            return self._drop(row, out, row["stage"] or "environment", f"docker: {str(exc)[:300]}")
        except (OSError, ValueError, KeyError, tomllib.TOMLDecodeError) as exc:
            return self._drop(row, out, row["stage"] or "files", f"{type(exc).__name__}: {str(exc)[:300]}")

    def _environment(self, src: Path, source: Source, task: str, env: dict) -> tuple[str, dict]:
        image = env.get("docker_image")
        if image:
            self.docker.pull(image)
            pinned = self.docker.pinned_ref(image)
            return pinned, {"kind": "pulled", "upstream": image, "pinned": pinned}
        dockerfile = src / "environment" / "Dockerfile"
        if not dockerfile.is_file():
            raise ValueError("no environment docker_image and no environment/Dockerfile")
        tag = f"openbench-{source.name}-{task}:env".lower()
        self.docker.build(str(src / "environment"), tag)
        bases = {}
        for base in _dockerfile_bases(dockerfile):
            try:
                bases[base] = self.docker.pinned_ref(base)
            except DockerError:
                bases[base] = None
        return tag, {"kind": "built", "tag": tag, "image_id": self.docker.image_id(tag), "bases": bases}

    def _write_files(self, src: Path, out: Path, meta: dict, workdir: str) -> None:
        shutil.copy2(src / "instruction.md", out / "instruction.md")
        shutil.copytree(src / "tests", out / "checker_data" / "tests")
        solution = src / "solution"
        if not (solution / "solve.sh").is_file():
            raise ValueError("no solution/solve.sh")
        shutil.copytree(solution, out / "checker_data" / "oracle")
        (out / "solution").mkdir()
        shutil.copy2(solution / "solve.sh", out / "solution" / "solve.sh")

    def _provenance(self, out: Path, source: Source, task: str, env: dict, tag: str, derived_id: str, workdir: str) -> None:
        env_line = (f"- **Environment image**: pulled `{env['upstream']}`, pinned to `{env['pinned']}`" if env["kind"] == "pulled"
                    else f"- **Environment image**: built from upstream `environment/` as `{env['tag']}` (`{env['image_id']}`); "
                         f"bases: {json.dumps(env['bases'])}")
        (out / "PROVENANCE.md").write_text("\n".join([
            "# Provenance", "", f"- **Upstream**: {source.repo} @ `{source.commit}`, task `{task}`",
            f"- **License**: {source.license} (upstream `LICENSE`)", env_line,
            f"- **Task image (agent + checker)**: `{tag}` (`{derived_id}`), recipe `checker_data/image/Dockerfile`: the "
            "environment plus verifier dependencies primed at build time; then `UV_OFFLINE=1 PIP_NO_INDEX=1`",
            f"- **Workspace**: copied from the environment image's WORKDIR `{workdir}`",
            "- **Checker**: upstream `tests/test.sh` with `--network none`; reward from `/logs/verifier/reward.txt`. "
            "With the solution overlay it runs the upstream `solution/solve.sh` (`checker_data/oracle/`) first.",
            "- **Admission**: imported by `obench.taskimport.pipeline`; untouched workspace fails, solution passes, no network.",
            ""]), encoding="utf-8")

    def _drop(self, row: dict, out: Path, stage: str, reason: str) -> dict:
        row.update({"status": "dropped", "stage": stage, "reason": reason})
        if out.exists():
            dest = self.out_root / "_dropped" / out.parent.name / out.name
            if dest.exists():
                shutil.rmtree(dest)
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(out), str(dest))
        return row


def run(plan_doc: dict, out_root: Path, report_path: Path, importer: Importer | None = None,
        only: set | None = None, retry: bool = False) -> list[dict]:
    """Import every ``import`` entry; resumable via the report (finished tasks skipped unless ``retry``)."""
    importer = importer or Importer(out_root)
    sources = {s["name"]: Source(s["name"], Path(s["root"]), s["repo"], s["commit"], s.get("license", "Apache-2.0"))
               for s in plan_doc["sources"]}
    done = {} if retry else {(r["source"], r["task"]): r for r in read_report(report_path)}
    rows = []
    for entry in plan_doc["entries"]:
        if entry["decision"] != "import" or (only and entry["task"] not in only):
            continue
        key = (entry["source"], entry["task"])
        if key in done:
            continue
        row = importer.import_task(entry, sources[entry["source"]])
        with Path(report_path).open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(row, sort_keys=True) + "\n")
        rows.append(row)
    return rows


def read_report(path: Path) -> list[dict]:
    if not Path(path).exists():
        return []
    latest = {}
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        if line.strip():
            row = json.loads(line)
            latest[(row["source"], row["task"])] = row
    return list(latest.values())


def summarize(plan_doc: dict, report_rows: list[dict]) -> dict:
    by_source = {}
    for s in plan_doc["sources"]:
        entries = [e for e in plan_doc["entries"] if e["source"] == s["name"]]
        rows = [r for r in report_rows if r["source"] == s["name"]]
        by_source[s["name"]] = {
            "repo": s["repo"], "commit": s["commit"], "candidates": len(entries),
            "duplicates": sorted(f"{e['task']} ({e['decision']} of {e['duplicate_of']})" for e in entries
                                 if e["decision"].startswith("duplicate")),
            "planned": sum(e["decision"] == "import" for e in entries),
            "admitted": sorted(r["task"] for r in rows if r["status"] == "admitted"),
            "dropped": sorted((r["task"], r["stage"], r["reason"]) for r in rows if r["status"] == "dropped"),
            "pending": sum(e["decision"] == "import" for e in entries) - len(rows),
        }
    return by_source


def write_report_md(plan_doc: dict, report_rows: list[dict], path: Path) -> str:
    summary = summarize(plan_doc, report_rows)
    lines = ["# Task import report", "", "| Source | Pin | Candidates | Duplicates removed | Imported | Admitted | Dropped | Pending |",
             "|---|---|---:|---:|---:|---:|---:|---:|"]
    for name, s in summary.items():
        lines.append(f"| {name} | `{s['commit'][:12]}` | {s['candidates']} | {len(s['duplicates'])} | {s['planned']} | "
                     f"{len(s['admitted'])} | {len(s['dropped'])} | {s['pending']} |")
    for name, s in summary.items():
        lines += ["", f"## {name}", "", f"{s['repo']} @ `{s['commit']}`", ""]
        if s["duplicates"]:
            lines += ["**Duplicates removed:**", *[f"- {d}" for d in s["duplicates"]], ""]
        if s["dropped"]:
            lines += ["**Dropped:**", "", "| Task | Stage | Reason |", "|---|---|---|",
                      *[f"| {t} | {st} | {r.replace('|', '/')} |" for t, st, r in s["dropped"]], ""]
        lines += [f"**Admitted ({len(s['admitted'])}):** " + ", ".join(s["admitted"]), ""]
    text = "\n".join(lines) + "\n"
    Path(path).write_text(text, encoding="utf-8")
    return text


def _parse_source(spec: str) -> Source:
    """``name=ROOT@REPO@COMMIT``"""
    name, rest = spec.split("=", 1)
    root, repo, commit = rest.split("@", 2)
    return Source(name, Path(root), repo, commit)


def main(argv: list[str] | None = None) -> int:
    import argparse

    parser = argparse.ArgumentParser(description="Import + no-network validation of Harbor tasks")
    sub = parser.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("plan")
    p.add_argument("--source", action="append", required=True, help="name=ROOT@REPO_URL@COMMIT, in priority order")
    p.add_argument("--repo-root", type=Path, default=Path("."))
    p.add_argument("--out", type=Path, required=True, help="plan.json")
    r = sub.add_parser("run")
    r.add_argument("--plan", type=Path, required=True)
    r.add_argument("--out", type=Path, required=True, help="tasks root, e.g. tasks-imported")
    r.add_argument("--report", type=Path, required=True)
    r.add_argument("--only", nargs="*", default=None)
    r.add_argument("--retry", action="store_true")
    r.add_argument("--platform", default="linux/amd64")
    m = sub.add_parser("report")
    m.add_argument("--plan", type=Path, required=True)
    m.add_argument("--report", type=Path, required=True)
    m.add_argument("--out", type=Path, required=True, help="IMPORT_REPORT.md")
    args = parser.parse_args(argv)
    if args.cmd == "plan":
        doc = plan([_parse_source(s) for s in args.source], args.repo_root)
        args.out.write_text(json.dumps(doc, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        counts = {}
        for e in doc["entries"]:
            counts.setdefault(e["source"], {}).setdefault(e["decision"], 0)
            counts[e["source"]][e["decision"]] += 1
        print(json.dumps(counts, sort_keys=True))
        return 0
    doc = json.loads(args.plan.read_text(encoding="utf-8"))
    if args.cmd == "run":
        rows = run(doc, args.out, args.report, Importer(args.out, Docker(platform=args.platform)),
                   set(args.only) if args.only else None, args.retry)
        print(json.dumps({"admitted": sum(r["status"] == "admitted" for r in rows),
                          "dropped": sum(r["status"] == "dropped" for r in rows)}))
        return 0
    print(write_report_md(doc, read_report(args.report), args.out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
