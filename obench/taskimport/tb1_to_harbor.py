"""Convert Terminal-Bench 1 tasks (``task.yaml`` format) to Harbor task dirs.

TB1 core 0.1.1 (``laude-institute/terminal-bench`` @ 91e10457, ``./tasks``)
uses the old layout:
- ``task.yaml``: instruction, difficulty, timeouts, tags;
- ``Dockerfile`` and ``docker-compose.yaml``: the environment;
- ``run-tests.sh`` plus ``tests/``: the verifier, which reads ``$TEST_DIR``;
- ``solution.sh`` or ``solution.yaml``: the reference solution.

Harbor's layout, which ``obench.taskimport.pipeline`` reads:

    task.toml  instruction.md  environment/Dockerfile (+ build context)
    tests/test.sh (+ test files)  solution/solve.sh

The generated ``tests/test.sh`` sets ``TEST_DIR=/tests``, runs the upstream
``run-tests.sh``, and writes ``/logs/verifier/reward.txt`` (1 iff it exits
0), the Harbor verifier contract.

Tasks that can't become one Harbor container are refused with a reason:
- more than one compose service (multi-container);
- an interactive ``solution.yaml`` (``append_enter: false`` keystrokes);
- no instruction, no Dockerfile, or no tests.

YAML: PyYAML when installed (``pip install pyyaml`` on the VM). Otherwise
JSON-syntax YAML only, which is enough for the tests.
"""

from __future__ import annotations

import json
import re
import shutil
from dataclasses import dataclass, field
from pathlib import Path

TB1_REPO = "https://github.com/laude-institute/terminal-bench"
TB1_CORE_COMMIT = "91e10457b5410f16c44364da1a34cb6de8c488a5"
_SKIP_IN_CONTEXT = {"tests", "task.yaml", "docker-compose.yaml", "run-tests.sh", "solution.sh", "solution.yaml"}

TEST_SH = """#!/bin/bash
# Generated by obench.taskimport.tb1_to_harbor: Harbor verifier wrapper around TB1's run-tests.sh.
export TEST_DIR=/tests
mkdir -p /logs/verifier
bash /tests/run-tests.sh
if [ $? -eq 0 ]; then echo 1 > /logs/verifier/reward.txt; else echo 0 > /logs/verifier/reward.txt; fi
"""


class ConvertError(ValueError):
    pass


def load_yaml(text: str):
    try:
        import yaml  # type: ignore
    except ImportError:
        try:
            return json.loads(text)
        except json.JSONDecodeError as exc:
            raise ConvertError("PyYAML is not installed (pip install pyyaml) and the file is not JSON-syntax YAML") from exc
    return yaml.safe_load(text)


@dataclass
class Converted:
    task: str
    ok: bool
    reasons: list = field(default_factory=list)
    out: str | None = None


def _instruction(meta: dict) -> str | None:
    if isinstance(meta.get("instruction"), str) and meta["instruction"].strip():
        return meta["instruction"]
    for desc in meta.get("descriptions") or []:
        if isinstance(desc, dict) and desc.get("key", "base") == "base" and isinstance(desc.get("description"), str):
            return desc["description"]
    return None


def _services(compose_text: str) -> list[str]:
    try:
        doc = load_yaml(compose_text)
    except ConvertError:
        # Fall back to counting top-level service keys (two-space indent under "services:").
        block = compose_text.split("services:", 1)[-1]
        return re.findall(r"(?m)^  ([A-Za-z0-9_.-]+):\s*$", block)
    return sorted((doc or {}).get("services") or {})


def solution_script(task_dir: Path) -> tuple[str | None, str | None]:
    """``(solve.sh text, refusal reason)``."""
    sh = task_dir / "solution.sh"
    if sh.is_file():
        return sh.read_text(encoding="utf-8"), None
    yml = task_dir / "solution.yaml"
    if not yml.is_file():
        return None, "no solution.sh or solution.yaml"
    steps = load_yaml(yml.read_text(encoding="utf-8")) or []
    lines = ["#!/bin/bash", "# Generated from solution.yaml by obench.taskimport.tb1_to_harbor"]
    for i, step in enumerate(steps):
        if not isinstance(step, dict) or not isinstance(step.get("command"), str):
            return None, f"solution.yaml step {i} has no command"
        if step.get("append_enter", True) is False:
            return None, f"interactive solution.yaml (step {i} types keystrokes without Enter)"
        lines.append(step["command"].strip())
    return "\n".join(lines) + "\n", None


def task_toml(task: str, meta: dict, commit: str) -> str:
    def q(value) -> str:
        return json.dumps(str(value))
    tags = ", ".join(q(t) for t in meta.get("tags") or [])
    return "\n".join([
        'schema_version = "1.1"', "", "[task]", f"name = {q('terminal-bench-core/' + task)}", "",
        "[metadata]", f"difficulty = {q(meta.get('difficulty', 'unknown'))}",
        f"category = {q(meta.get('category', 'unknown'))}", f"tags = [{tags}]",
        f"upstream_repo = {q(TB1_REPO)}", f"upstream_commit = {q(commit)}", f"upstream_path = {q('tasks/' + task)}", "",
        "[verifier]", f"timeout_sec = {float(meta.get('max_test_timeout_sec', 180))}", "",
        "[agent]", f"timeout_sec = {float(meta.get('max_agent_timeout_sec', 1800))}", "",
        "[environment]", "allow_internet = true", "",
    ])


def convert_task(task_dir: Path, out_root: Path, commit: str = TB1_CORE_COMMIT) -> Converted:
    task_dir, task = Path(task_dir), Path(task_dir).name
    reasons = []
    meta_path = task_dir / "task.yaml"
    meta = load_yaml(meta_path.read_text(encoding="utf-8")) if meta_path.is_file() else None
    instruction = _instruction(meta) if isinstance(meta, dict) else None
    if not instruction:
        reasons.append("no instruction in task.yaml")
    if not (task_dir / "Dockerfile").is_file():
        reasons.append("no Dockerfile")
    if not (task_dir / "run-tests.sh").is_file() or not (task_dir / "tests").is_dir():
        reasons.append("no run-tests.sh or tests/")
    compose = task_dir / "docker-compose.yaml"
    if compose.is_file():
        services = _services(compose.read_text(encoding="utf-8"))
        if len(services) > 1:
            reasons.append(f"multi-container ({len(services)} compose services: {', '.join(services)})")
    solve, why = solution_script(task_dir)
    if why:
        reasons.append(why)
    if reasons:
        return Converted(task, False, reasons)
    out = Path(out_root) / task
    if out.exists():
        shutil.rmtree(out)
    (out / "environment").mkdir(parents=True)
    for item in task_dir.iterdir():
        if item.name in _SKIP_IN_CONTEXT:
            continue
        dest = out / "environment" / item.name
        shutil.copytree(item, dest) if item.is_dir() else shutil.copy2(item, dest)
    shutil.copytree(task_dir / "tests", out / "tests")
    shutil.copy2(task_dir / "run-tests.sh", out / "tests" / "run-tests.sh")
    (out / "tests" / "test.sh").write_text(TEST_SH, encoding="utf-8")
    (out / "solution").mkdir()
    (out / "solution" / "solve.sh").write_text(solve, encoding="utf-8")
    (out / "instruction.md").write_text(instruction.rstrip() + "\n", encoding="utf-8")
    (out / "task.toml").write_text(task_toml(task, meta, commit), encoding="utf-8")
    return Converted(task, True, [], str(out))


def core_ids(registry_path: Path, version: str = "0.1.1") -> list[str]:
    """TB1 core task ids from terminal-bench's ``registry.json``."""
    registry = json.loads(Path(registry_path).read_text(encoding="utf-8"))
    for entry in registry:
        if entry.get("name") == "terminal-bench-core" and entry.get("version") == version:
            return list(entry["task_id_subset"])
    raise ConvertError(f"terminal-bench-core {version} not in {registry_path}")


def main(argv: list[str] | None = None) -> int:
    import argparse

    parser = argparse.ArgumentParser(description="Convert TB1 tasks to Harbor task dirs")
    parser.add_argument("--src", type=Path, required=True, help="terminal-bench checkout's tasks/ dir at the pin")
    parser.add_argument("--registry", type=Path, required=True, help="terminal-bench registry.json (core id list)")
    parser.add_argument("--version", default="0.1.1")
    parser.add_argument("--commit", default=TB1_CORE_COMMIT)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    args.out.mkdir(parents=True, exist_ok=True)
    results = [convert_task(args.src / task, args.out, args.commit) for task in core_ids(args.registry, args.version)]
    report = [{"task": r.task, "ok": r.ok, "reasons": r.reasons} for r in results]
    (args.out / "convert-report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"converted": sum(r.ok for r in results), "refused": sum(not r.ok for r in results)}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
